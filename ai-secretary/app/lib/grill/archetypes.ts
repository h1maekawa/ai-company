/**
 * Topic別 Design Tree 原型（archetype）。
 *
 * 目的: どのtopicでも「目的／対象／方法／スケジュール」のような汎用Treeになるのを防ぐ。
 * - LLMが使えるときは questions.ts のプロンプトが topic 固有のTreeを生成する。
 * - LLMが落ちた/未設定のときも、topicに応じた**意味のあるTree**へフォールバックする。
 *   （テスト環境や障害時に汎用Treeへ退化させないための安全網）
 *
 * 判定は決定論的なキーワードスコアリング（D7の「判断はコード」原則）。
 */

import type { GrillNode } from "./types";

export type ArchetypeId =
  | "sales"
  | "software"
  | "business"
  | "investment"
  | "productivity"
  | "generic";

type NodeSeed = {
  id: string;
  title: string;
  question: string;
  dependsOn: string[];
  options: [string, string][]; // [label, description]（1件目が推奨案）
  recommendation: string;
  reason: string;
};

function toNodes(seeds: NodeSeed[]): GrillNode[] {
  return seeds.map((s) => ({
    id: s.id,
    title: s.title,
    question: s.question,
    dependsOn: s.dependsOn,
    status: "blocked" as const,
    options: s.options.map(([label, description], i) => ({
      index: i + 1,
      label,
      description,
      isRecommended: i === 0,
    })),
    recommendation: s.recommendation,
    recommendationReason: s.reason,
    children: [],
  }));
}

