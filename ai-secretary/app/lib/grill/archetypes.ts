/** topicから最も近いarchetypeを決定論的に選ぶ（判断はコード・D7）。 */
export function detectArchetype(topic: string): ArchetypeId {
  const t = (topic || "").toLowerCase();
  let best: ArchetypeId = "generic";
  let bestScore = 0;
  for (const [id, words] of Object.entries(KEYWORDS) as [Exclude<ArchetypeId, "generic">, string[]][]) {
    let score = 0;
    for (const w of words) if (t.includes(w)) score += w.length >= 4 ? 2 : 1;
    if (score > bestScore) {
      bestScore = score;
      best = id;
    }
  }
  return best;
}

/** archetypeに対応する Design Tree を返す（LLM不使用・決定論的）。 */
export function archetypeTree(archetype: ArchetypeId): GrillNode[] {
  if (archetype === "generic") return toNodes(GENERIC);
  return toNodes(ARCHETYPES[archetype]);
}

/** topicから直接フォールバックTreeを作る。 */
export function fallbackTreeForTopic(topic: string): { nodes: GrillNode[]; archetype: ArchetypeId } {
  const archetype = detectArchetype(topic);
  return { nodes: archetypeTree(archetype), archetype };
}
